#!/usr/bin/env python3
"""Generate port/include/p2_sdk_aliases.h: decomp-era Dolphin SDK enum/constant names that Aurora
spells differently or lacks, mapped onto Aurora's names (same enum type and value) or, failing
that, onto the decomp's numeric value.

Run from the repo root: python3 tools/pc/gen_sdk_aliases.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DECOMP = ROOT / "include/Dolphin"
AURORA = ROOT / "extern/aurora/include/dolphin"


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def decomp_part(text):
    # forwarders keep the original header under "#else // TARGET_PC"
    if "#else // TARGET_PC" in text:
        text = text.split("#else // TARGET_PC", 1)[1]
    return text


def eval_expr(expr, env):
    e = expr.strip()
    e = re.sub(r"\b(0x[0-9A-Fa-f]+|\d+)[uUlL]*\b", r"\1", e)
    for name in sorted(env, key=len, reverse=True):
        e = re.sub(r"\b%s\b" % re.escape(name), "(%d)" % env[name], e)
    if re.search(r"[A-Za-z_]", re.sub(r"0x[0-9A-Fa-f]+", "", e)):
        raise ValueError(expr)
    return int(eval(e, {"__builtins__": {}}))


def parse_enums(text):
    """-> {enum_type: [(name, value)]}, {name: value}"""
    enums, flat = {}, {}
    for m in re.finditer(r"typedef\s+enum\s*\w*\s*\{(.*?)\}\s*(\w+)\s*;|enum\s+(\w+)\s*\{(.*?)\}\s*;", text, re.S):
        body = m.group(1) if m.group(1) is not None else m.group(4)
        tname = m.group(2) or m.group(3)
        val = -1
        items = []
        for part in body.split(","):
            part = part.strip()
            if not part or part.startswith("#"):
                continue
            mm = re.match(r"(\w+)\s*(?:=\s*(.+))?$", part, re.S)
            if not mm:
                continue
            name, expr = mm.group(1), mm.group(2)
            try:
                val = eval_expr(expr, flat) if expr else val + 1
            except Exception:
                continue
            items.append((name, val))
            flat[name] = val
        enums.setdefault(tname, []).extend(items)
    return enums, flat


def parse_defines(text):
    out = {}
    for m in re.finditer(r"^\s*#\s*define\s+(\w+)\s+([^\n]+)$", text, re.M):
        name, val = m.group(1), m.group(2).strip()
        if "(" in name:
            continue
        out[name] = val
    return out


def load(root, decomp):
    enums, flat, defines, alltext = {}, {}, {}, ""
    for p in sorted(root.rglob("*.h")):
        t = p.read_text(errors="replace")
        if decomp:
            t = decomp_part(t)
        t = strip_comments(t)
        alltext += t + "\n"
        e, f = parse_enums(t)
        for k, v in e.items():
            enums.setdefault(k, []).extend(v)
        flat.update(f)
        defines.update(parse_defines(t))
    return enums, flat, defines, alltext


d_enums, d_flat, d_defs, _ = load(DECOMP, True)
a_enums, a_flat, a_defs, a_text = load(AURORA, False)
a_names = set(re.findall(r"\b\w+\b", a_text))

# Only emit names the game (outside the SDK itself) actually uses, so macros cannot collide
# with unrelated identifiers.
# Hand-maintained in p2_sdk_compat.h instead (host values differ).
MANUAL = {"GX_FIFO_OBJ_SIZE"}

used = set()
for p in list((ROOT / "src").rglob("*.c*")) + list((ROOT / "include").rglob("*.h")):
    rp = p.relative_to(ROOT).as_posix()
    if rp.startswith(("include/Dolphin/", "src/Dolphin/")) or "PowerPC_EABI_Support" in rp:
        continue
    used.update(re.findall(r"\b[A-Z_][A-Z0-9_]+\b", p.read_text(errors="replace")))

lines = ["// Generated by tools/pc/gen_sdk_aliases.py; do not edit by hand.",
         "// Decomp-era Dolphin SDK names, mapped onto Aurora's spelling (same enum type and value).",
         "#ifndef _P2_SDK_ALIASES_H", "#define _P2_SDK_ALIASES_H", ""]
n_alias = n_value = 0
for tname, items in d_enums.items():
    aitems = a_enums.get(tname, [])
    by_val = {}
    for n, v in aitems:
        by_val.setdefault(v, n)
    for name, val in items:
        if name in a_names or name not in used or name in MANUAL:
            continue
        if val in by_val:
            lines.append(f"#define {name} {by_val[val]}")
            n_alias += 1
        elif aitems:
            lines.append(f"#define {name} (({tname}){val})")
            n_value += 1
        else:
            lines.append(f"#define {name} ({val})")
            n_value += 1
lines.append("")
n_def = 0
for name, val in d_defs.items():
    if name in a_names or name not in used or name in MANUAL or name.startswith("_") or name.endswith("_H") or "TARGET_PC" in val:
        continue
    if not re.fullmatch(r"\(?\s*-?(0x[0-9A-Fa-f]+|\d+)[uUlL]*\s*\)?", val):
        continue  # only plain numeric constants; anything else is handled by hand
    lines.append(f"#define {name} {val}")
    n_def += 1
lines += ["", "#endif", ""]
(ROOT / "port/include/p2_sdk_aliases.h").write_text("\n".join(lines))
print(f"{n_alias} enum aliases, {n_value} value fallbacks, {n_def} numeric defines")
