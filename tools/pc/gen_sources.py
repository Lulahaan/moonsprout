#!/usr/bin/env python3
"""Generate cmake/sources.cmake from configure.py's library/object lists.

Run from the repo root: python3 tools/pc/gen_sources.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Dolphin SDK / PPC runtime libraries replaced on PC by Aurora, the host C runtime, or port/sdk.
EXCLUDED_LIBS = {
    "TRK_MINNOW_DOLPHIN", "Runtime", "MSL_C", "OdemuExi2", "amcstubs", "odenotstub", "db",
    "vi", "ar", "base", "card", "dsp", "dvd", "exi", "gd", "gx", "mtx", "os", "pad", "si", "ai", "thp", "gba",
}

# Individual files replaced on PC.
EXCLUDED_FILES = {
    # JAudio's DSP task management talks to the GameCube DSP; port/audio replaces it.
    "JSystem/JAudio/dsp/dspproc.c", "JSystem/JAudio/dsp/dsptask.c",
    "JSystem/JAudio/dsp/osdsp.c", "JSystem/JAudio/dsp/osdsp_task.c",
}

text = (ROOT / "configure.py").read_text()
libs = {}
for block in re.split(r'\n    \{\n', text)[1:]:
    m = re.search(r'"lib":\s*"([^"]+)"', block)
    if not m:
        continue
    name = m.group(1)
    objs = re.findall(r'Object\([^"]*"([^"]+\.(?:c|cpp))"', block)
    libs[name] = objs

out = ["# Generated by tools/pc/gen_sources.py from configure.py; do not edit by hand.", ""]
names = []
for name, objs in libs.items():
    if name in EXCLUDED_LIBS:
        continue
    srcs = [f"src/{o}" for o in objs if (ROOT / "src" / o).exists() and o not in EXCLUDED_FILES]
    if not srcs:
        continue
    var = "P2_LIB_" + re.sub(r"\W", "_", name)
    names.append(var)
    out.append(f"set({var}")
    out += [f"    {s}" for s in srcs]
    out.append(")\n")
out.append("set(P2_LIBS " + " ".join(names) + ")")
(ROOT / "cmake").mkdir(exist_ok=True)
(ROOT / "cmake" / "sources.cmake").write_text("\n".join(out) + "\n")
total = sum(len(libs[n]) for n in libs if n not in EXCLUDED_LIBS)
print(f"{len(names)} libs, {total} objects -> cmake/sources.cmake")
